func testExecutionControlSchemaDown(t *testing.T, harness *postgresHarness) {
	t.Helper()
	_, ownerURL := harness.ownerDatabase(t)
	requireSchema(t, ownerURL, nil)
	path := filepath.Join(
		harness.moduleDir,
		"internal",
		"schemamigrations",
		"migrations",
		"00004_execution_control_schema.sql",
	)
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read execution-control schema migration: %v", err)
	}
	_, downSQL, found := strings.Cut(string(raw), "-- +goose Down")
	if !found {
		t.Fatal("execution-control schema migration has no down section")
	}
	conn := connect(t, ownerURL)
	defer closeConn(t, conn)
	if _, err := conn.Exec(t.Context(), downSQL); err != nil {
		t.Fatalf("apply execution-control schema down migration: %v", err)
	}
	var targetSchemaExists bool
	if err := conn.QueryRow(
		t.Context(),
		"select to_regnamespace('execution_control') is not null",
	).Scan(&targetSchemaExists); err != nil {
		t.Fatalf("inspect execution_control schema after down migration: %v", err)
	}
	if targetSchemaExists {
		t.Fatal("execution_control schema remains after down migration")
	}
	for _, table := range append([]string{"execution_config.model_settings"}, compatibilityRuntimeViews()...) {
		var kind string
		if err := conn.QueryRow(t.Context(), `
			select class.relkind::text from pg_class as class where class.oid = to_regclass($1)
		`, table).Scan(&kind); err != nil {
			t.Fatalf("inspect restored table %s: %v", table, err)
		}
		if kind != "r" {
			t.Fatalf("restored relation %s kind = %q, want table", table, kind)
		}
	}
}

func testSchemaCommandRejectsUnknownRuntimeSchema(t *testing.T, harness *postgresHarness, binaryPath string) {
	t.Helper()
	tests := []struct {
		name    string
		prepare func(*testing.T, string)
	}{
		{
			name: "partial legacy table",
			prepare: func(t *testing.T, databaseURL string) {
				installAppAPIRuntimeFact(t, databaseURL)
				conn := connect(t, databaseURL)
				defer closeConn(t, conn)
				if _, err := conn.Exec(t.Context(), "create table runtime.agent_run_cleanups (run_id text primary key)"); err != nil {
					t.Fatalf("install partial legacy runtime fixture: %v", err)
				}
			},
		},
		{
			name: "unknown table",
			prepare: func(t *testing.T, databaseURL string) {
				installAppAPIRuntimeFact(t, databaseURL)
				conn := connect(t, databaseURL)
				defer closeConn(t, conn)
				if _, err := conn.Exec(t.Context(), "create table runtime.unowned_runtime_state (id text primary key)"); err != nil {
					t.Fatalf("install unknown runtime table fixture: %v", err)
				}
			},
		},
		{
			name: "unknown column",
			prepare: func(t *testing.T, databaseURL string) {
				installAppAPIRuntimeFact(t, databaseURL)
				installLegacyRuntimeSchema(t, harness, databaseURL, true)
				conn := connect(t, databaseURL)
				defer closeConn(t, conn)
				if _, err := conn.Exec(t.Context(), "alter table runtime.agent_runs add column unexpected_column text"); err != nil {
					t.Fatalf("install unknown runtime column fixture: %v", err)
				}
			},
		},
		{
			name: "missing legacy column",
			prepare: func(t *testing.T, databaseURL string) {
				installAppAPIRuntimeFact(t, databaseURL)
				installLegacyRuntimeSchema(t, harness, databaseURL, true)
				conn := connect(t, databaseURL)
				defer closeConn(t, conn)
				if _, err := conn.Exec(t.Context(), "alter table runtime.agent_run_cleanups drop column confirmed_at"); err != nil {
					t.Fatalf("remove legacy runtime column fixture: %v", err)
				}
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			_, databaseURL := harness.ownerDatabase(t)
			test.prepare(t, databaseURL)
			evidencePath := filepath.Join(t.TempDir(), "failed-install-evidence.json")
			if output, err := runSchemaCommand(t, harness, binaryPath, databaseURL, "install", evidencePath); err == nil {
				t.Fatalf("schema install unexpectedly succeeded: %s", output)
			}
			if _, err := os.Stat(evidencePath); !errors.Is(err, os.ErrNotExist) {
				t.Fatalf("failed schema install evidence stat error = %v, want not exist", err)
			}
			assertExecutionControlMigrationLedgerAbsent(t, databaseURL)
		})
	}
}

func runSchemaCommand(
	t *testing.T,
	harness *postgresHarness,
	binaryPath, databaseURL, mode, evidencePath string,
	extraArgs ...string,
) ([]byte, error) {
	t.Helper()
	keyringPath, encryptionKeyPath := writeIntegrationProviderSecrets(t)
	args := []string{
		"--mode", mode,
		"--database-url", databaseURL,
		"--evidence-path", evidencePath,
		"--provider-config-keyring-path", keyringPath,
		"--provider-config-encryption-key-path", encryptionKeyPath,
	}
	command := exec.CommandContext(t.Context(), binaryPath, append(args, extraArgs...)...)
	command.Dir = harness.moduleDir
	return command.CombinedOutput()
}

func requireSuccessfulSchemaCommand(
	t *testing.T,
	harness *postgresHarness,
	binaryPath, databaseURL, mode string,
	extraArgs ...string,
) {
	t.Helper()
	evidencePath := filepath.Join(t.TempDir(), mode+"-evidence.json")
	if output, err := runSchemaCommand(t, harness, binaryPath, databaseURL, mode, evidencePath, extraArgs...); err != nil {
		t.Fatalf("run schema command %s: %v\n%s", mode, err, output)
	}
	raw, err := os.ReadFile(evidencePath)
	if err != nil {
		t.Fatalf("read schema evidence: %v", err)
	}
	var evidence schemaEvidence
	if err := json.Unmarshal(raw, &evidence); err != nil {
		t.Fatalf("decode schema evidence: %v", err)
	}
	if evidence.Mode != mode || !evidence.Passed || !evidence.SchemaReady ||
		evidence.Store != "postgres" || evidence.GeneratedAt == "" {
		t.Fatalf("schema evidence = %#v", evidence)
	}
}

