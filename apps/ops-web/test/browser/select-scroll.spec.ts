import { expect, test } from "@playwright/test";

test("桌面选择菜单展开时页面仍能滚动，键盘和外部关闭保持可用", async ({ page }) => {
	await page.setViewportSize({ width: 1024, height: 480 });
	await page.goto("/requests");
	const control = page.getByRole("combobox", { name: "时间范围", exact: true });
	await control.click();
	await expect(page.getByRole("listbox")).toBeVisible();
	const before = await page.evaluate(() => window.scrollY);
	await page.mouse.move(1000, 450);
	await page.mouse.wheel(0, 160);
	await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(before);
	await expect(page.getByRole("listbox")).toBeVisible();
	await page.keyboard.press("Escape");
	await expect(page.getByRole("listbox")).toBeHidden();
	await expect(control).toBeFocused();
	await control.press("ArrowDown");
	await expect(page.getByRole("listbox")).toBeVisible();
	await page.keyboard.press("Home");
	await page.keyboard.press("Enter");
	await expect(page.getByRole("listbox")).toBeHidden();
	await expect(control).toBeFocused();
	await control.click();
	await expect(page.getByRole("option", { selected: true })).toBeFocused();
	await page.keyboard.press("Tab");
	await expect(page.getByRole("listbox")).toBeHidden();
	await expect(control).not.toBeFocused();
	await control.click();
	await page.getByRole("heading", { level: 1 }).click();
	await expect(page.getByRole("listbox")).toBeHidden();
	await expect(page.locator("body")).not.toHaveAttribute("data-scroll-locked");
});

test("弹窗内选择器保留弹窗滚动边界，Esc 只关闭选项", async ({ page }) => {
	await page.setViewportSize({ width: 1024, height: 600 });
	await page.goto("/dining/menu");
	await page.getByRole("button", { name: "新增菜品", exact: true }).click();
	const dialog = page.getByRole("dialog", { name: "新增菜品" });
	const control = dialog.getByRole("combobox").first();
	await control.click();
	const list = dialog.getByRole("listbox");
	await expect(list).toBeVisible();
	await list.hover();
	await page.mouse.wheel(0, 200);
	await expect.poll(() => list.evaluate((element) => element.scrollTop)).toBeGreaterThan(0);
	await expect(page.locator("body")).toHaveAttribute("data-scroll-locked", "1");
	await page.keyboard.press("Escape");
	await expect(page.getByRole("listbox")).toBeHidden();
	await expect(dialog).toBeVisible();
	await expect(control).toBeFocused();
	await control.click();
	const option = page.getByRole("option").last();
	const label = await option.innerText();
	await option.click();
	await expect(control).toHaveText(label);
	await expect(control).toBeFocused();
	await expect(dialog).toBeVisible();
	await dialog.getByRole("button", { name: "取消", exact: true }).click();
	await expect(page.locator("body")).not.toHaveAttribute("data-scroll-locked");
});
