import { describe, expect, it } from "vitest";

import { campusWebManualChunks } from "../config/manual-chunks";

describe("campus web manual chunks", () => {
	it("keeps mature auth UI dependencies out of route chunks", () => {
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/@better-auth-ui/heroui/dist/index.js",
			),
		).toBeUndefined();
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/@better-auth-ui/react/dist/index.js",
			),
		).toBe("better-auth-ui-core-vendor");
		expect(
			campusWebManualChunks("/repo/apps/campus-web/node_modules/better-auth/dist/client.js"),
		).toBe("better-auth-runtime-vendor");
		expect(
			campusWebManualChunks("/repo/apps/campus-web/node_modules/@heroui/react/dist/index.js"),
		).toBe("heroui-react-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/@heroui/react/dist/components/calendar/calendar.js",
			),
		).toBe("heroui-form-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/@heroui/react/dist/components/textfield/textfield.js",
			),
		).toBe("heroui-form-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/@heroui/react/dist/components/list-box/list-box.js",
			),
		).toBe("heroui-form-vendor");
		expect(
			campusWebManualChunks("/repo/apps/campus-web/node_modules/@heroui/styles/dist/index.js"),
		).toBe("heroui-styles-vendor");
		expect(
			campusWebManualChunks("/repo/apps/campus-web/node_modules/tailwind-variants/dist/index.js"),
		).toBe("heroui-styles-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/tailwind-merge/dist/bundle-mjs.mjs",
			),
		).toBe("heroui-styles-vendor");
		expect(
			campusWebManualChunks("/repo/apps/campus-web/node_modules/@gravity-ui/icons/dist/index.js"),
		).toBe("gravity-icons-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/react-aria-components/dist/index.js",
			),
		).toBe("react-aria-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/react-aria/dist/private/utils/useId.mjs",
			),
		).toBe("react-aria-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/@react-stately/utils/dist/import.mjs",
			),
		).toBe("react-aria-vendor");
		expect(
			campusWebManualChunks(
				"/repo/apps/campus-web/node_modules/react-stately/dist/private/utils/useControlledState.mjs",
			),
		).toBe("react-aria-vendor");
	});
});
