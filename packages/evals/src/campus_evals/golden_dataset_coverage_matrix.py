from __future__ import annotations

import argparse
from pathlib import Path

from campus_evals.rag_eval_coverage import (
    CURRENT_RAG_CONSUMPTION_SURFACES,
    EXCLUDED_RAG_DENOMINATOR_SURFACES,
    RAG_EVAL_COVERAGE_REPORT_SCHEMA_VERSION,
    RagEvalCoverageReport,
    RagEvalSurfaceCoverage,
    build_rag_eval_coverage_report,
)

GOLDEN_DATASET_COVERAGE_MATRIX_GENERATOR = "campus_evals.golden_dataset_coverage_matrix"


class GoldenDatasetCoverageMatrixDriftError(ValueError):
    """Raised when the tracked matrix no longer matches generated eval truth."""


def render_golden_dataset_coverage_matrix(
    *,
    repo_root: str | Path | None = None,
) -> str:
    report = build_rag_eval_coverage_report(repo_root=repo_root)
    _validate_report(report)
    lines = [
        "---",
        "doc_type: reference",
        "status: active",
        f"generated_by: {GOLDEN_DATASET_COVERAGE_MATRIX_GENERATOR}",
        f"source_report_schema: {RAG_EVAL_COVERAGE_REPORT_SCHEMA_VERSION}",
        "---",
        "<!-- markdownlint-disable MD013 -->",
        "# Golden Dataset Coverage Matrix",
        "",
        "This file is generated from repo-owned deterministic eval truth. It records the",
        "current RAG denominator and the golden dataset coverage that must stay aligned",
        "with retrieval qrels, release acceptance fixtures, answer-quality fixtures,",
        "known-gap fixtures and maturity policy.",
        "",
        "Do not edit this file by hand. Update the eval fixtures or coverage policy, then",
        "regenerate it with:",
        "",
        "```bash",
        "uv run --all-packages python -m campus_evals.golden_dataset_coverage_matrix --write docs/reference/golden-dataset-case-matrix.md",
        "```",
        "",
        "## Current RAG Denominator",
        "",
        "| Surface | Profile | Artifact | Qrels | Expected docs | Release acceptance | Answer quality | Golden qrels | Known gaps | Maturity |",
        "| ------- | ------- | -------- | ----- | ------------- | ------------------ | -------------- | ------------ | ---------- | -------- |",
    ]
    for surface in report.surfaces:
        lines.append(_surface_summary_row(surface))
    lines.extend(
        [
            "",
            "## Surface Details",
            "",
        ]
    )
    for surface in report.surfaces:
        lines.extend(_surface_detail_lines(surface))
    lines.extend(
        [
            "## Excluded Surfaces",
            "",
            "| Surface | Reason |",
            "| ------- | ------ |",
        ]
    )
    for surface_key, reason in sorted(report.excluded_surfaces.items()):
        lines.append(f"| `{surface_key}` | `{reason}` |")
    lines.extend(
        [
            "",
            "## Operating Rules",
            "",
            "- The denominator is exactly the current query-enabled RAG consumption surface set.",
            "- Runtime observations, RAGAS diagnostics and panel displays can only supplement",
            "  this matrix; they do not author canonical golden truth.",
            "- Missing canonical documents remain explicit known gaps or backlog work; consumers",
            "  must not infer replacement truth from adjacent documents.",
            "- `official_web/fresh_news` remains outside the current RAG denominator unless the",
            "  denominator policy and serving surface are explicitly changed together.",
            "",
        ]
    )
    return "\n".join(lines)


def check_golden_dataset_coverage_matrix(
    path: str | Path,
    *,
    repo_root: str | Path | None = None,
) -> None:
    matrix_path = Path(path)
    expected = render_golden_dataset_coverage_matrix(repo_root=repo_root)
    actual = matrix_path.read_text(encoding="utf-8")
    if actual != expected:
        raise GoldenDatasetCoverageMatrixDriftError(
            f"golden dataset coverage matrix drifted: {matrix_path}"
        )


def write_golden_dataset_coverage_matrix(
    path: str | Path,
    *,
    repo_root: str | Path | None = None,
) -> None:
    matrix_path = Path(path)
    matrix_path.parent.mkdir(parents=True, exist_ok=True)
    matrix_path.write_text(
        render_golden_dataset_coverage_matrix(repo_root=repo_root),
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate or check the golden dataset coverage matrix."
    )
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", metavar="PATH", help="Check a tracked matrix for drift.")
    action.add_argument("--write", metavar="PATH", help="Write the generated matrix.")
    args = parser.parse_args(argv)

    if args.check is not None:
        check_golden_dataset_coverage_matrix(args.check)
    if args.write is not None:
        write_golden_dataset_coverage_matrix(args.write)
    return 0


def _validate_report(report: RagEvalCoverageReport) -> None:
    if report.schema_version != RAG_EVAL_COVERAGE_REPORT_SCHEMA_VERSION:
        raise ValueError(
            "golden matrix requires "
            f"{RAG_EVAL_COVERAGE_REPORT_SCHEMA_VERSION}, got {report.schema_version}"
        )
    surface_keys = tuple(surface.surface_key for surface in report.surfaces)
    if surface_keys != CURRENT_RAG_CONSUMPTION_SURFACES:
        raise ValueError(
            "golden matrix requires current RAG denominator surfaces: "
            + ", ".join(CURRENT_RAG_CONSUMPTION_SURFACES)
        )
    if report.excluded_surfaces != EXCLUDED_RAG_DENOMINATOR_SURFACES:
        raise ValueError("golden matrix excluded surfaces differ from denominator policy")
    if not report.passed:
        raise ValueError("golden matrix cannot render while RAG eval coverage has gaps")
    if not report.maturity_passed:
        raise ValueError("golden matrix cannot render while RAG eval maturity has gaps")


def _surface_summary_row(surface: RagEvalSurfaceCoverage) -> str:
    return (
        f"| `{surface.surface_key}` | `{surface.profile_id}` | "
        f"`{surface.profile_artifact_kind}` | {surface.qrels_case_count} | "
        f"{surface.unique_expected_doc_count} | {surface.release_acceptance_case_count} | "
        f"{surface.answer_quality_case_count} | {surface.golden_qrels_case_count} | "
        f"{surface.known_gap_case_count} | `{surface.maturity_status}` |"
    )


def _surface_detail_lines(surface: RagEvalSurfaceCoverage) -> list[str]:
    backlog_case_types = ", ".join(f"`{item}`" for item in surface.backlog_case_types)
    if not backlog_case_types:
        backlog_case_types = "`none`"
    gaps = _status_list(surface.gaps)
    maturity_gaps = _status_list(surface.maturity_gaps)
    return [
        f"### `{surface.surface_key}`",
        "",
        "| Dimension | Current value | Source |",
        "| --------- | ------------- | ------ |",
        f"| Profile | `{surface.profile_id}` | profile registry |",
        f"| Artifact kind | `{surface.profile_artifact_kind}` | profile registry |",
        f"| Qrels cases | {surface.qrels_case_count} | `{surface.qrels_fixture}` |",
        f"| Unique expected docs | {surface.unique_expected_doc_count} | qrels expected sources |",
        (
            "| Release acceptance cases | "
            f"{surface.release_acceptance_case_count} | "
            f"`{surface.release_acceptance_fixture}` |"
        ),
        (
            "| Release baseline gate | "
            f"{_yes_no(surface.has_release_baseline_gate)} | profile policy |"
        ),
        (
            "| Answer quality cases | "
            f"{surface.answer_quality_case_count} | answer-quality fixture set |"
        ),
        (f"| Golden qrels cases | {surface.golden_qrels_case_count} | golden qrels fixture set |"),
        f"| Known-gap cases | {surface.known_gap_case_count} | `{surface.known_gap_fixture}` |",
        (
            "| Maturity target | "
            f"{surface.recommended_target_case_count} qrels / "
            f"{surface.recommended_release_acceptance_case_count} release / "
            f"{surface.recommended_unique_expected_doc_count} docs | "
            f"`{surface.maturity_backlog_fixture}` |"
        ),
        f"| Backlog case types | {backlog_case_types} | maturity backlog |",
        f"| Coverage gaps | {gaps} | coverage report |",
        f"| Maturity gaps | {maturity_gaps} | coverage report |",
        "",
    ]


def _status_list(items: tuple[str, ...]) -> str:
    if items:
        return ", ".join(f"`{item}`" for item in items)
    return "`none`"


def _yes_no(value: bool) -> str:
    return "`yes`" if value else "`no`"


__all__ = [
    "GOLDEN_DATASET_COVERAGE_MATRIX_GENERATOR",
    "GoldenDatasetCoverageMatrixDriftError",
    "check_golden_dataset_coverage_matrix",
    "main",
    "render_golden_dataset_coverage_matrix",
    "write_golden_dataset_coverage_matrix",
]


if __name__ == "__main__":
    raise SystemExit(main())
